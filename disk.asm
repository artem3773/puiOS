disk_load:
    push dx
    mov ah, 0x02        ; Функция BIOS: чтение секторов
    mov al, dh          ; Количество секторов для чтения (передается через DH)
    mov ch, 0x00        ; Цилиндр 0
    mov dh, 0x00        ; Головка 0
    mov cl, 0x02        ; Начинаем со 2-го сектора (1-й занят бутлоадером)
    int 0x13            ; Вызов прерывания BIOS
    jc disk_error       ; Если ошибка (флаг CF=1) — зависаем
    pop dx
    ret

disk_error:
    jmp $               ; Бесконечный цикл в случае ошибки диска